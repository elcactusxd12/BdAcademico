    private void JTABLE_Mant_PabellonesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_JTABLE_Mant_PabellonesMouseClicked
         txtnombrepabellon.setEnabled(true);

    /* Obtener la fila seleccionada */
    int filaseleccionada =
            JTABLE_Mant_Pabellones.getSelectedRow();

    if (filaseleccionada >= 0) {

        /* Obtener código */
        String codigo =
                JTABLE_Mant_Pabellones
                        .getValueAt(filaseleccionada, 0)
                        .toString();

        /* Obtener nombre del pabellón */
        String pabellon =
                JTABLE_Mant_Pabellones
                        .getValueAt(filaseleccionada, 1)
                        .toString();

        /* Colocar datos en los campos */
        txtcodigopabellon.setText(codigo);
        txtnombrepabellon.setText(pabellon);

        /* Habilitar modificar */
        BTN_Modificar.setEnabled(true);

        /* Deshabilitar guardar */
        BTN_Guardar.setEnabled(false);
    }
    }//GEN-LAST:event_JTABLE_Mant_PabellonesMouseClicked

