    private void BTN_GuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTN_GuardarActionPerformed

         /* 1. Obtener nombre */
    String pabellon =
            txtnombrepabellon.getText().trim();

    /* 2. Validar */
    if (pabellon.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Ingrese el nombre del pabellón",
                "Campo requerido",
                JOptionPane.WARNING_MESSAGE
        );

        txtnombrepabellon.requestFocus();

        return;
    }

    /* 3. Confirmar */
    int respuesta = JOptionPane.showConfirmDialog(
            this,
            "¿Desea guardar el registro de pabellón?",
            "Confirmación",
            JOptionPane.YES_NO_OPTION
    );

    if (respuesta == JOptionPane.YES_OPTION) {

        try {

            /* 4. Insertar */
            conexionBD.insertarPabellon(pabellon);

            /* 5. Mensaje */
            JOptionPane.showMessageDialog(
                    this,
                    "Pabellón registrado correctamente",
                    "Registro exitoso",
                    JOptionPane.INFORMATION_MESSAGE
            );

            /* 6. Actualizar tabla */
            this.mostrarPabellones();

            /* 7. Limpiar */
            txtcodigopabellon.setText("");
            txtnombrepabellon.setText("");

            /* 8. Deshabilitar */
            txtnombrepabellon.setEnabled(false);
            BTN_Guardar.setEnabled(false);

        } catch (SQLException ex) {

            JOptionPane.showMessageDialog(
                    this,
                    "Error al registrar pabellón:\n"
                    + ex.getMessage(),
                    "Error de base de datos",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }
    }//GEN-LAST:event_BTN_GuardarActionPerformed

    private void BTN_ModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTN_ModificarActionPerformed
         /* 1. Obtener datos */
    String codStr =
            txtcodigopabellon.getText().trim();

    String nuevoNombre =
            txtnombrepabellon.getText().trim();

    /* 2. Validar */
    if (codStr.isEmpty() || nuevoNombre.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Seleccione un pabellón y complete el nuevo nombre",
                "Campo requerido",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    /* 3. Convertir código */
    int codigo;

    try {

        codigo = Integer.parseInt(codStr);

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "El código del pabellón no es válido",
                "Error",
                JOptionPane.ERROR_MESSAGE
        );

        return;
    }

    /* 4. Confirmar */
    int respuesta = JOptionPane.showConfirmDialog(
            this,
            "¿Desea modificar este pabellón?",
            "Confirmación",
            JOptionPane.YES_NO_OPTION
    );

    if (respuesta == JOptionPane.YES_OPTION) {

        try {

            /* 5. Modificar */
            conexionBD.modificarPabellon(
                    codigo,
                    nuevoNombre
            );

            /* 6. Mensaje */
            JOptionPane.showMessageDialog(
                    this,
                    "Pabellón modificado correctamente",
                    "Modificación exitosa",
                    JOptionPane.INFORMATION_MESSAGE
            );

            /* 7. Actualizar tabla */
            this.mostrarPabellones();

            /* 8. Limpiar */
            txtcodigopabellon.setText("");
            txtnombrepabellon.setText("");

            /* 9. Deshabilitar */
            BTN_Modificar.setEnabled(false);
            BTN_Guardar.setEnabled(false);

        } catch (SQLException ex) {

            JOptionPane.showMessageDialog(
                    this,
                    "Error al modificar pabellón:\n"
                    + ex.getMessage(),
                    "Error de base de datos",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }
    }//GEN-LAST:event_BTN_ModificarActionPerformed

