    private void TXT_BuscarPabellonesKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_TXT_BuscarPabellonesKeyReleased
          /* Limpiar tabla */
    modeloTablaPabellon.setRowCount(0);

    /* Obtener texto */
    String nombre =
            TXT_BuscarPabellones.getText().trim();

    try {

        /* Buscar */
        ResultSet rs =
                conexionBD.buscarPabellon(nombre);

        while (rs.next()) {

            Object[] fila = {
                rs.getInt("codigo"),
                rs.getString("pabellon")
            };

            modeloTablaPabellon.addRow(fila);
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error al buscar pabellones:\n"
                + e.getMessage(),
                "Error de consulta",
                JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_TXT_BuscarPabellonesKeyReleased

