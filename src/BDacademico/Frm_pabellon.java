public void mostrarPabellones() {

    // Ordenar ASC, DSC
    JTABLE_Mant_Pabellones.setAutoCreateRowSorter(true);

    // Limpiar la tabla
    modeloTablaPabellon.setRowCount(0);

    try {

        // Obtener los pabellones
        ResultSet rs =
                conexionBD.listarPabellones();

        // Recorrer resultados
        while (rs.next()) {

            Object[] fila = {
                rs.getInt("codigo"),
                rs.getString("pabellon")
            };

            // Agregar fila
            modeloTablaPabellon.addRow(fila);
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error al mostrar pabellones:\n"
                + e.getMessage(),
                "Error de consulta",
                JOptionPane.ERROR_MESSAGE
        );
    }
}

