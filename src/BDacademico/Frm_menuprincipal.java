    // Cuadro de color con icono blanco
    private class IconoCuadrado extends JComponent {

        private final Icon icono;
        private final Color color;

        IconoCuadrado(
                FontAwesomeSolid ico,
                int tamano,
                Color color) {

            this.color = color;
            this.icono = FontIcon.of(
                    ico, tamano / 2, Color.WHITE);

            setPreferredSize(new Dimension(tamano, tamano));
            setMinimumSize(new Dimension(tamano, tamano));
            setMaximumSize(new Dimension(tamano, tamano));
            setOpaque(false);
        }

        @Override
        protected void paintComponent(Graphics g) {
            super.paintComponent(g);

            Graphics2D g2 = (Graphics2D) g.create();

            g2.setRenderingHint(
                    RenderingHints.KEY_ANTIALIASING,
                    RenderingHints.VALUE_ANTIALIAS_ON);

            g2.setColor(color);

            g2.fillRoundRect(
                    0, 0, getWidth() - 1, getHeight() - 1, 12, 12);

            if (icono != null) {
                int x = (getWidth() - icono.getIconWidth()) / 2;
                int y = (getHeight() - icono.getIconHeight()) / 2;

                icono.paintIcon(this, g2, x, y);
            }

            g2.dispose();
        }
    }

    // Círculo de color con icono blanco
    private class IconoCircular extends JComponent {

        private final Icon icono;
        private final Color color;

        IconoCircular(
                FontAwesomeSolid ico,
                int tamano,
                Color color) {

            this.icono = FontIcon.of(
                    ico, tamano / 2, Color.WHITE);

            this.color = color;

            setPreferredSize(new Dimension(tamano, tamano));
        }

        @Override
        protected void paintComponent(Graphics g) {
            super.paintComponent(g);

            Graphics2D g2 = (Graphics2D) g.create();

            g2.setRenderingHint(
                    RenderingHints.KEY_ANTIALIASING,
                    RenderingHints.VALUE_ANTIALIAS_ON);

            g2.setColor(color);

            g2.fillOval(
                    0, 0, getWidth() - 1, getHeight() - 1);

            icono.paintIcon(
                    this,
                    g2,
                    (getWidth() - icono.getIconWidth()) / 2,
                    (getHeight() - icono.getIconHeight()) / 2);

            g2.dispose();
        }
    }
