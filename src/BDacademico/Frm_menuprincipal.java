    // Maximizar o restaurar la ventana
    private void alternarMaximizado() {
        if ((getExtendedState() & JFrame.MAXIMIZED_BOTH)
                == JFrame.MAXIMIZED_BOTH) {

            setExtendedState(JFrame.NORMAL);
            setSize(1200, 700);
            setLocationRelativeTo(null);

        } else {
            setExtendedState(JFrame.MAXIMIZED_BOTH);
        }
    }

    // Permite mover la ventana arrastrando el encabezado
    private void habilitarArrastre(JComponent zona) {
        MouseAdapter ma = new MouseAdapter() {
            @Override
            public void mousePressed(MouseEvent e) {
                mouseInicio = e.getLocationOnScreen();
                ventanaInicio = getLocation();
            }

            @Override
            public void mouseDragged(MouseEvent e) {
                if ((getExtendedState() & JFrame.MAXIMIZED_BOTH)
                        == JFrame.MAXIMIZED_BOTH) {
                    return;
                }

                Point p = e.getLocationOnScreen();

                setLocation(
                        ventanaInicio.x + p.x - mouseInicio.x,
                        ventanaInicio.y + p.y - mouseInicio.y);
            }

            @Override
            public void mouseClicked(MouseEvent e) {
                if (e.getClickCount() == 2) {
                    alternarMaximizado();
                }
            }
        };

        zona.addMouseListener(ma);
        zona.addMouseMotionListener(ma);
    }

    // Botón personalizado de minimizar, maximizar y cerrar
    private class BotonVentana extends JComponent {

        private final Icon icono;
        private final Color colorHover;
        private boolean hover = false;
        private final Runnable accion;

        BotonVentana(
                FontAwesomeSolid ico,
                Color colorHover,
                Runnable accion) {

            this.icono = FontIcon.of(ico, 12, Color.WHITE);
            this.colorHover = colorHover;
            this.accion = accion;

            setPreferredSize(new Dimension(42, 30));
            setCursor(new Cursor(Cursor.HAND_CURSOR));

            addMouseListener(new MouseAdapter() {
                @Override
                public void mouseEntered(MouseEvent e) {
                    hover = true;
                    repaint();
                }

                @Override
                public void mouseExited(MouseEvent e) {
                    hover = false;
                    repaint();
                }

                @Override
                public void mouseClicked(MouseEvent e) {
                    BotonVentana.this.accion.run();
                }
            });
        }

        @Override
        protected void paintComponent(Graphics g) {
            Graphics2D g2 = (Graphics2D) g.create();

            if (hover) {
                g2.setColor(colorHover);
                g2.fillRect(0, 0, getWidth(), getHeight());
            }

            icono.paintIcon(
                    this,
                    g2,
                    (getWidth() - icono.getIconWidth()) / 2,
                    (getHeight() - icono.getIconHeight()) / 2);

            g2.dispose();
        }
    }

