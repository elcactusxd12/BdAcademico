    // Botón personalizado para los accesos rápidos
   
private class BotonAcceso extends JPanel {

    private boolean hover = false;
    private final Color color;
    private final IconoCuadrado icono;

    BotonAcceso(
            String texto,
            FontAwesomeSolid ico,
            Color color,
            Runnable accion) {

        this.color = color;

        setOpaque(false);
        setLayout(new GridBagLayout());
        setCursor(new Cursor(Cursor.HAND_CURSOR));

        setToolTipText(texto);

        icono = new IconoCuadrado(ico, 48, color);
        add(icono);

        MouseAdapter eventos = new MouseAdapter() {
            @Override
            public void mouseEntered(MouseEvent e) {
                hover = true;
                repaint();
            }

            @Override
            public void mouseExited(MouseEvent e) {
                hover = false;
                repaint();
            }

            @Override
            public void mouseClicked(MouseEvent e) {
                accion.run();
            }
        };

        addMouseListener(eventos);
        icono.addMouseListener(eventos);
    }

    @Override
    protected void paintComponent(Graphics g) {
        super.paintComponent(g);

        Graphics2D g2 = (Graphics2D) g.create();

        g2.setRenderingHint(
                RenderingHints.KEY_ANTIALIASING,
                RenderingHints.VALUE_ANTIALIAS_ON);

        g2.setColor(
                hover ? new Color(232, 240, 253) : Color.WHITE);

        g2.fillRoundRect(
                0, 0, getWidth() - 1, getHeight() - 1, 16, 16);

        g2.setColor(
                hover ? color : new Color(214, 224, 240));

        g2.drawRoundRect(
                0, 0, getWidth() - 1, getHeight() - 1, 16, 16);

        g2.dispose();
    }
}
