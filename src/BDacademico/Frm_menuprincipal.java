    private class ItemMenu extends JComponent {

        private final String texto;
        private final Icon icono;
        private boolean seleccionado = false;
        private boolean hover = false;

        ItemMenu(String texto, FontAwesomeSolid ico) {
            this.texto = texto;
            this.icono = FontIcon.of(ico, 18, Color.WHITE);

            setCursor(new Cursor(Cursor.HAND_CURSOR));

            addMouseListener(new MouseAdapter() {
                @Override
                public void mouseEntered(MouseEvent e) {
                    hover = true;
                    repaint();
                }

                @Override
                public void mouseExited(MouseEvent e) {
                    hover = false;
                    repaint();
                }
            });
        }

        void setSeleccionado(boolean s) {
            seleccionado = s;
            repaint();
        }

        @Override
        protected void paintComponent(Graphics g) {
            Graphics2D g2 = (Graphics2D) g.create();

            g2.setRenderingHint(
                    RenderingHints.KEY_ANTIALIASING,
                    RenderingHints.VALUE_ANTIALIAS_ON);

            g2.setRenderingHint(
                    RenderingHints.KEY_TEXT_ANTIALIASING,
                    RenderingHints.VALUE_TEXT_ANTIALIAS_ON);

            if (seleccionado) {
                g2.setColor(new Color(37, 99, 235));
                g2.fillRoundRect(
                        0, 0, getWidth(), getHeight(), 12, 12);
            } else if (hover) {
                g2.setColor(new Color(255, 255, 255, 28));
                g2.fillRoundRect(
                        0, 0, getWidth(), getHeight(), 12, 12);
            }

            int iy = (getHeight() - icono.getIconHeight()) / 2;
            icono.paintIcon(this, g2, 18, iy);

            g2.setFont(new Font(
                    "Segoe UI",
                    seleccionado ? Font.BOLD : Font.PLAIN,
                    12));

            g2.setColor(Color.WHITE);

            FontMetrics fm = g2.getFontMetrics();
            int ty = (getHeight() - fm.getHeight()) / 2
                    + fm.getAscent();

            g2.drawString(texto, 54, ty);
            g2.dispose();
        }
    }

