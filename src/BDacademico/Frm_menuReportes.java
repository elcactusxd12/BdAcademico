    private JPanel crearTarjeta(
            String titulo,
            String descripcion,
            FontAwesomeSolid icono,
            Color color,
            Runnable accion) {

        JPanel tarjeta = new JPanel(new BorderLayout(8, 8)) {

            private boolean hover = false;

            {
                addMouseListener(new MouseAdapter() {
                    @Override
                    public void mouseClicked(MouseEvent e) {
                        accion.run();
                    }

                    @Override
                    public void mouseEntered(MouseEvent e) {
                        hover = true;
                        repaint();
                    }

                    @Override
                    public void mouseExited(MouseEvent e) {
                        hover = false;
                        repaint();
                    }
                });
            }

            @Override
            protected void paintComponent(Graphics g) {
                super.paintComponent(g);

                Graphics2D g2 = (Graphics2D) g.create();
                g2.setRenderingHint(
                        RenderingHints.KEY_ANTIALIASING,
                        RenderingHints.VALUE_ANTIALIAS_ON);

                Color colorInicial = hover
                        ? color.brighter()
                        : color;

                Color colorFinal = hover
                        ? color.darker()
                        : color.darker().darker();

                g2.setPaint(new GradientPaint(
                        0, 0, colorInicial,
                        getWidth(), getHeight(), colorFinal));

                g2.fillRoundRect(
                        0, 0,
                        getWidth() - 1,
                        getHeight() - 1,
                        22, 22);

                g2.setColor(new Color(255, 255, 255, 90));
                g2.drawRoundRect(
                        0, 0,
                        getWidth() - 2,
                        getHeight() - 2,
                        22, 22);

                g2.dispose();
            }
        };

        tarjeta.setOpaque(false);
        tarjeta.setBorder(
                BorderFactory.createEmptyBorder(14, 12, 14, 12));
        tarjeta.setCursor(new Cursor(Cursor.HAND_CURSOR));

        JLabel lblIcono = new JLabel(
                FontIcon.of(icono, 38, Color.WHITE));

        lblIcono.setHorizontalAlignment(SwingConstants.CENTER);

        JLabel lblTitulo = new JLabel(titulo);
        lblTitulo.setFont(new Font("Segoe UI", Font.BOLD, 15));
        lblTitulo.setForeground(Color.WHITE);
        lblTitulo.setHorizontalAlignment(SwingConstants.CENTER);

        JLabel lblDescripcion = new JLabel(
                "<html><div style='text-align:center;'>"
                + descripcion
                + "</div></html>");

        lblDescripcion.setFont(
                new Font("Segoe UI", Font.PLAIN, 11));
        lblDescripcion.setForeground(Color.WHITE);
        lblDescripcion.setHorizontalAlignment(
                SwingConstants.CENTER);

        JPanel panelTexto = new JPanel(new GridLayout(2, 1, 0, 5));
        panelTexto.setOpaque(false);
        panelTexto.add(lblTitulo);
        panelTexto.add(lblDescripcion);

        tarjeta.add(lblIcono, BorderLayout.NORTH);
        tarjeta.add(panelTexto, BorderLayout.CENTER);

        // Permite hacer clic también sobre el contenido de la tarjeta
        MouseAdapter eventos = new MouseAdapter() {
            @Override
            public void mouseClicked(MouseEvent e) {
                accion.run();
            }

            @Override
            public void mouseEntered(MouseEvent e) {
                tarjeta.putClientProperty("hover", true);
                tarjeta.repaint();
            }

            @Override
            public void mouseExited(MouseEvent e) {
                tarjeta.putClientProperty("hover", false);
                tarjeta.repaint();
            }
        };

        lblIcono.addMouseListener(eventos);
        lblTitulo.addMouseListener(eventos);
        lblDescripcion.addMouseListener(eventos);

        return tarjeta;
    }

