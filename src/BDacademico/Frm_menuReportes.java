    private void abrirReporteEstudiantes() {

        String sql =
                "SELECT "
              + "e.id_estudiante, e.dni, e.nombres, e.apellidos, "
              + "d.nombre_distrito, g.nombre_genero, "
              + "e.fecha_nacimiento, e.correo1, e.correo2, "
              + "e.telefono1, e.telefono2, "
              + "p.descripcion AS procedencia, "
              + "co.nombre_condicion, "
              + "CONCAT_WS(' ', ap.nombres, ap.apellidos) AS apoderado, "
              + "CASE WHEN e.estado = 1 "
              + "THEN 'Activo' ELSE 'Inactivo' END AS estado "
              + "FROM estudiante e "
              + "LEFT JOIN distrito d "
              + "ON e.id_distrito = d.id_distrito "
              + "LEFT JOIN genero g "
              + "ON e.id_genero = g.id_genero "
              + "LEFT JOIN procedencia p "
              + "ON e.id_procedencia = p.id_procedencia "
              + "LEFT JOIN condicion co "
              + "ON e.id_condicion = co.id_condicion "
              + "LEFT JOIN apoderado ap "
              + "ON e.id_apoderado = ap.id_apoderado "
              + "ORDER BY e.apellidos, e.nombres";

        mostrarReporte("Reporte de estudiantes", sql);
    }

    // =========================================================
    // 9. REPORTE DE MATRÍCULAS
    // =========================================================

    private void abrirReporteMatriculas() {

        String sql =
                "SELECT "
              + "m.id_matricula, e.dni, e.nombres, e.apellidos, "
              + "c.nombre_carrera, t.descripcion AS turno, "
              + "s.nombre_semestre, ci.nombre_ciclo, "
              + "m.fecha_matricula, "
              + "CASE WHEN m.estado_pago = 1 "
              + "THEN 'Pagado' ELSE 'Pendiente' END AS estado_pago, "
              + "m.numero_operacion "
              + "FROM matricula m "
              + "INNER JOIN estudiante e "
              + "ON m.id_estudiante = e.id_estudiante "
              + "INNER JOIN carrera c "
              + "ON m.id_carrera = c.id_carrera "
              + "INNER JOIN turno t "
              + "ON m.id_turno = t.id_turno "
              + "INNER JOIN semestre s "
              + "ON m.id_semestre = s.id_semestre "
              + "INNER JOIN ciclo ci "
              + "ON m.id_ciclo = ci.id_ciclo "
              + "ORDER BY m.fecha_matricula DESC";

        mostrarReporte("Reporte de matrículas", sql);
    }

    // =========================================================
    // 10. REPORTE DE PLAN DE ESTUDIOS
    // =========================================================

    private void abrirReportePlanEstudios() {

        String sql =
                "SELECT "
              + "pe.id_plan_estudios, c.nombre_curso, "
              + "ca.nombre_carrera, ci.nombre_ciclo, "
              + "s.nombre_semestre, pe.numero_semanas, "
              + "pe.horas_tecnologia, pe.horas_taller, "
              + "pe.creditos, pe.observaciones "
              + "FROM plan_estudios pe "
              + "INNER JOIN curso c "
              + "ON pe.id_curso = c.id_curso "
              + "INNER JOIN carrera ca "
              + "ON pe.id_carrera = ca.id_carrera "
              + "INNER JOIN ciclo ci "
              + "ON pe.id_ciclo = ci.id_ciclo "
              + "INNER JOIN semestre s "
              + "ON pe.id_semestre = s.id_semestre "
              + "ORDER BY ca.nombre_carrera, ci.id_ciclo";

        mostrarReporte("Reporte de plan de estudios", sql);
    }

    // =========================================================
    // 11. REPORTE DE CONTROL DE PAGOS
    // =========================================================

    private void abrirReportePagos() {

        String sql =
                "SELECT "
              + "cp.id_control_pagos, e.dni, e.nombres, e.apellidos, "
              + "tp.concepto_pago AS tipo_pago, cp.concepto, "
              + "cp.numero_operacion, cp.fecha_registro, "
              + "cp.importe, cp.total, cp.observaciones "
              + "FROM control_pagos cp "
              + "INNER JOIN estudiante e "
              + "ON cp.id_estudiante = e.id_estudiante "
              + "INNER JOIN tipo_pago tp "
              + "ON cp.id_tipo_pago = tp.id_tipo_pago "
              + "ORDER BY cp.fecha_registro DESC";

        mostrarReporte("Reporte de control de pagos", sql);
    }

