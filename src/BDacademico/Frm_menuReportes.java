    // =========================================================
    // 16. REPORTE DE USUARIOS
    // =========================================================

    private void abrirReporteUsuarios() {

        String sql =
                "SELECT "
              + "u.id_usuario, u.codigo, c.nombre_cargo, "
              + "CASE WHEN u.estado_usuario = 1 "
              + "THEN 'Activo' ELSE 'Inactivo' END AS estado, "
              + "u.fecha_registro "
              + "FROM usuario u "
              + "LEFT JOIN cargo c ON u.id_cargo = c.id_cargo "
              + "ORDER BY u.codigo";

        // Por seguridad, el reporte no incluye las contraseñas.
        mostrarReporte("Reporte de usuarios", sql);
    }

    // =========================================================
    // 17. VENTANA GENERAL DE LOS REPORTES
    // =========================================================

    private void mostrarReporte(String titulo, String sql) {

        JFrame ventana = new JFrame(titulo);
        ventana.setSize(1100, 620);
        ventana.setLocationRelativeTo(this);
        ventana.setDefaultCloseOperation(JFrame.DISPOSE_ON_CLOSE);
        ventana.setLayout(new BorderLayout(0, 0));

        // Encabezado del reporte
        JPanel encabezado = new JPanel(new BorderLayout());
        encabezado.setBackground(HEADER_1);
        encabezado.setBorder(
                BorderFactory.createEmptyBorder(15, 20, 15, 20));

        JLabel lblTitulo = new JLabel(titulo.toUpperCase());
        lblTitulo.setFont(new Font("Segoe UI", Font.BOLD, 20));
        lblTitulo.setForeground(Color.WHITE);

        JLabel lblSubtitulo = new JLabel(
                "Sistema Académico  |  Reporte de información");
        lblSubtitulo.setFont(new Font("Segoe UI", Font.PLAIN, 12));
        lblSubtitulo.setForeground(TEXTO_SUAVE);

        JPanel textos = new JPanel(new GridLayout(2, 1, 0, 5));
        textos.setOpaque(false);
        textos.add(lblTitulo);
        textos.add(lblSubtitulo);

        encabezado.add(textos, BorderLayout.CENTER);

        // Tabla
        DefaultTableModel modelo = new DefaultTableModel() {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };

        JTable tabla = new JTable(modelo);
        tabla.setAutoCreateRowSorter(true);
        tabla.setRowHeight(27);
        tabla.setFont(new Font("Segoe UI", Font.PLAIN, 12));
        tabla.setForeground(new Color(45, 55, 75));
        tabla.setBackground(Color.WHITE);
        tabla.setSelectionBackground(new Color(190, 215, 250));
        tabla.setSelectionForeground(new Color(15, 40, 100));
        tabla.setGridColor(new Color(225, 230, 238));
        tabla.setShowVerticalLines(false);
        tabla.setFillsViewportHeight(true);

        // Encabezado de la tabla
        tabla.getTableHeader().setFont(
                new Font("Segoe UI", Font.BOLD, 12));
        tabla.getTableHeader().setBackground(
                new Color(30, 75, 145));
        tabla.getTableHeader().setForeground(Color.WHITE);
        tabla.getTableHeader().setOpaque(true);
        tabla.getTableHeader().setPreferredSize(
                new Dimension(0, 35));
        tabla.getTableHeader().setReorderingAllowed(false);

        // Filas alternadas y selección
        tabla.setDefaultRenderer(Object.class,
                new javax.swing.table.DefaultTableCellRenderer() {

            @Override
            public Component getTableCellRendererComponent(
                    JTable table,
                    Object value,
                    boolean isSelected,
                    boolean hasFocus,
                    int row,
                    int column) {

                Component componente =
                        super.getTableCellRendererComponent(
                                table, value, isSelected,
                                hasFocus, row, column);

                if (isSelected) {
                    componente.setBackground(
                            new Color(190, 215, 250));
                    componente.setForeground(
                            new Color(15, 40, 100));
                } else if (row % 2 == 0) {
                    componente.setBackground(Color.WHITE);
                    componente.setForeground(
                            new Color(45, 55, 75));
                } else {
                    componente.setBackground(
                            new Color(239, 245, 253));
                    componente.setForeground(
                            new Color(45, 55, 75));
                }

                setBorder(BorderFactory.createEmptyBorder(0, 8, 0, 8));
                return componente;
            }
        });

        JScrollPane scroll = new JScrollPane(tabla);
        scroll.setBorder(BorderFactory.createEmptyBorder(12, 15, 5, 15));
        scroll.getViewport().setBackground(Color.WHITE);

        // Barra inferior
        JPanel pie = new JPanel(new BorderLayout());
        pie.setBackground(new Color(238, 242, 247));
        pie.setBorder(
                BorderFactory.createEmptyBorder(10, 18, 12, 18));

        JLabel lblCantidad = new JLabel("Registros: 0");
        lblCantidad.setFont(new Font("Segoe UI", Font.BOLD, 12));
        lblCantidad.setForeground(HEADER_1);

        JPanel botones = new JPanel(
                new FlowLayout(FlowLayout.RIGHT, 10, 0));
        botones.setOpaque(false);

        JButton btnActualizar = crearBoton(
                "Actualizar", new Color(35, 105, 190));

        JButton btnImprimir = crearBoton(
                "Imprimir", new Color(22, 140, 120));

        JButton btnCerrar = crearBoton(
                "Cerrar", new Color(190, 50, 60));

        btnActualizar.addActionListener(e ->
                cargarDatosReporte(modelo, sql, lblCantidad, ventana));

        btnImprimir.addActionListener(e -> {
            try {
                boolean impreso = tabla.print(
                        JTable.PrintMode.FIT_WIDTH,
                        new java.text.MessageFormat(titulo),
                        new java.text.MessageFormat("Página {0}"));

                if (impreso) {
                    JOptionPane.showMessageDialog(
                            ventana,
                            "Reporte enviado a impresión.",
                            "Impresión",
                            JOptionPane.INFORMATION_MESSAGE);
                }

            } catch (java.awt.print.PrinterException ex) {
                JOptionPane.showMessageDialog(
                        ventana,
                        "Error al imprimir: " + ex.getMessage(),
                        "Error de impresión",
                        JOptionPane.ERROR_MESSAGE);
            }
        });

        btnCerrar.addActionListener(e -> ventana.dispose());

        botones.add(btnActualizar);
        botones.add(btnImprimir);
        botones.add(btnCerrar);

        pie.add(lblCantidad, BorderLayout.WEST);
        pie.add(botones, BorderLayout.EAST);

        ventana.add(encabezado, BorderLayout.NORTH);
        ventana.add(scroll, BorderLayout.CENTER);
        ventana.add(pie, BorderLayout.SOUTH);

        cargarDatosReporte(modelo, sql, lblCantidad, ventana);

        ventana.setLocationRelativeTo(this);
        ventana.setVisible(true);
    }

    // =========================================================
    // 18. CARGAR LOS DATOS DESDE MYSQL
    // =========================================================

    private void cargarDatosReporte(
            DefaultTableModel modelo,
            String sql,
            JLabel lblCantidad,
            JFrame ventana) {

        modelo.setRowCount(0);
        modelo.setColumnCount(0);

        Conexion_alexander conexion_BD =
                new Conexion_alexander();

        Connection cn = conexion_BD.getConexion();

        if (cn == null) {
            JOptionPane.showMessageDialog(
                    ventana,
                    "No se pudo conectar con la base de datos.",
                    "Error de conexión",
                    JOptionPane.ERROR_MESSAGE);
            return;
        }

        try (Statement st = cn.createStatement();
             ResultSet rs = st.executeQuery(sql)) {

            ResultSetMetaData meta = rs.getMetaData();
            int columnas = meta.getColumnCount();

            for (int i = 1; i <= columnas; i++) {
                modelo.addColumn(meta.getColumnLabel(i));
            }

            while (rs.next()) {
                Object[] fila = new Object[columnas];

                for (int i = 1; i <= columnas; i++) {
                    fila[i - 1] = rs.getObject(i);
                }

                modelo.addRow(fila);
            }

            lblCantidad.setText(
                    "Registros encontrados: " + modelo.getRowCount());

        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(
                    ventana,
                    "Error al cargar el reporte:\n" + ex.getMessage(),
                    "Error SQL",
                    JOptionPane.ERROR_MESSAGE);
        }
    }
