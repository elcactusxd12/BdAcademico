private void cargarGeneros() {
    try {
        jcomboboxGeneros.removeAllItems();
        jcomboboxGeneros.addItem("<<Seleccionar>>"); // Opción por defecto

        // Cargar los géneros desde la base de datos
        try (ResultSet rs = conexionBD.combobox_ListarGenerosApoderado()) {
            while (rs != null && rs.next()) {
                String nombreGenero = rs.getString("nombre_genero");

                if (nombreGenero != null) {
                    jcomboboxGeneros.addItem(nombreGenero.trim());
                }
            }
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Error al cargar géneros: " + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
}
    // Método para listar los apoderados
private void MostrarApoderados() {
    JTABLE_APODERADO.setAutoCreateRowSorter(true);

    // Limpiar la tabla antes de cargar nuevos datos
    dtm.setRowCount(0);

    try (ResultSet rs = conexionBD.listarApoderados()) {

        while (rs != null && rs.next()) {

            Object fila[] = {
                rs.getInt("id_apoderado"),
                rs.getString("dni"),
                rs.getString("apellidos"),
                rs.getString("nombres"),
                rs.getString("direccion_actual"),
                rs.getString("correo"),
                rs.getString("otro_contacto"),
                rs.getString("nombre_genero")
            };

            dtm.addRow(fila);
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(
            this,
            "Error al listar apoderados: " + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
}
