private int leerEntero(
        javax.swing.JTextField campo, String nombre) {

    String valor = campo.getText().trim();

    if (valor.isEmpty()) {
        throw new NumberFormatException(
                "Ingrese el valor de " + nombre + ".");
    }

    int numero = Integer.parseInt(valor);

    if (numero < 0) {
        throw new NumberFormatException(
                nombre + " no puede ser negativo.");
    }

    return numero;
}

private double leerDecimal(
        javax.swing.JTextField campo, String nombre) {

    String valor = campo.getText().trim();

    if (valor.isEmpty()) {
        throw new NumberFormatException(
                "Ingrese el valor de " + nombre + ".");
    }

    double numero = Double.parseDouble(valor.replace(',', '.'));

    if (!Double.isFinite(numero) || numero < 0) {
        throw new NumberFormatException(
                nombre + " debe ser un número válido no negativo.");
    }

    return numero;
}

