    private void TXT_BuscarAulasKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_TXT_BuscarAulasKeyReleased
        try {

        String buscar = TXT_BuscarAulas.getText().trim();

        modeloTablaAula.setRowCount(0);

        ResultSet rs = conexionBD.buscarAula(buscar);

        while (rs.next()) {

            Object[] fila = {
                rs.getInt("codigo"),
                rs.getString("aula")
            };

            modeloTablaAula.addRow(fila);
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error al buscar aulas: " + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }

    }//GEN-LAST:event_TXT_BuscarAulasKeyReleased

