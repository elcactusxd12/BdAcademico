    private void JTABLE_Mant_AulaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_JTABLE_Mant_AulaMouseClicked
        txtnumeroAula.setEnabled(true);

        /* Obtener la fila seleccionada */
        int filaseleccionada =
        JTABLE_Mant_Aula.getSelectedRow();

        if (filaseleccionada >= 0) {

            /* llenar los campos de texto con los datos de la fila */
            String codigo =
            JTABLE_Mant_Aula
            .getValueAt(filaseleccionada, 0)
            .toString();

            String nombre =
            JTABLE_Mant_Aula
            .getValueAt(filaseleccionada, 1)
            .toString();

            txtcodigoAula.setText(codigo);
            txtnumeroAula.setText(nombre);

            /* Habilitar el botón modificar */
            BTN_Modificar.setEnabled(true);

            /* Deshabilitar botón guardar */
            BTN_Guardar.setEnabled(false);
        }
    }//GEN-LAST:event_JTABLE_Mant_AulaMouseClicked

