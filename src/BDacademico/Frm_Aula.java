public void mostrarAulas() {

    modeloTablaAula.setRowCount(0);

    try {

        ResultSet rs = conexionBD.listarAulas();

        while (rs.next()) {

            Object[] fila = {
                rs.getInt("codigo"),
                rs.getString("aula")
            };

            modeloTablaAula.addRow(fila);
        }

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error al mostrar las aulas: " + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
}
