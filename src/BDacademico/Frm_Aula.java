    private void BTN_GuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTN_GuardarActionPerformed

       
    try {

        /* 1. Obtener datos del formulario */
        String numeroAula = txtnumeroAula.getText().trim();

        /* 2. Validar campo */
        if (numeroAula.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Ingrese el número del aula.",
                    "Validación",
                    JOptionPane.WARNING_MESSAGE
            );

            txtnumeroAula.requestFocus();
            return;
        }

        /* 3. Insertar aula */
        conexionBD.insertarAula(numeroAula);

        /* 4. Mensaje */
        JOptionPane.showMessageDialog(
                this,
                "Aula registrada correctamente."
        );

        /* 5. Limpiar */
        txtcodigoAula.setText("");
        txtnumeroAula.setText("");

        /* 6. Actualizar tabla */
        mostrarAulas();

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error al insertar el aula: " + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_BTN_GuardarActionPerformed

    private void BTN_ModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTN_ModificarActionPerformed
         try {

        /* 1. Obtener código */
        int codigo = Integer.parseInt(
                txtcodigoAula.getText().trim()
        );

        /* 2. Obtener nuevo número */
        String nuevoNumero = txtnumeroAula.getText().trim();

        /* 3. Validar */
        if (nuevoNumero.isEmpty()) {

            JOptionPane.showMessageDialog(
                    this,
                    "Ingrese el número del aula.",
                    "Validación",
                    JOptionPane.WARNING_MESSAGE
            );

            txtnumeroAula.requestFocus();
            return;
        }

        /* 4. Modificar */
        conexionBD.modificarAula(codigo, nuevoNumero);

        /* 5. Mensaje */
        JOptionPane.showMessageDialog(
                this,
                "Aula modificada correctamente."
        );

        /* 6. Limpiar */
        txtcodigoAula.setText("");
        txtnumeroAula.setText("");

        /* 7. Actualizar tabla */
        mostrarAulas();

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
                this,
                "El código del aula no es válido.",
                "Error",
                JOptionPane.ERROR_MESSAGE
        );

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
                this,
                "Error al modificar el aula: " + e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_BTN_ModificarActionPerformed

